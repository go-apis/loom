package gen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/go-apis/loom/schema"
)

// Access renders who may run what at the gateway as one Markdown
// document: every command and every generated read, by the name the
// gateway serves it under, with the @role names and @allow rules the
// schema declares for it and whether it is planned first (@plan). It is
// the schema's access contract in a form a person reviews — and, checked
// in, one a pull request shows a change to.
//
// It states what the schema declares and DefaultPolicy enforces. A
// deployment's own Policy can decide otherwise, and what it decides is
// not in the schema to print.
func Access(s *schema.Schema) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "# Who may run what: %s\n\n", s.Service)
	b.WriteString("Generated by `loom access` from the schema. Do not edit.\n\n")
	b.WriteString("Every operation also needs the caller to have the namespace it names, and a command needs the caller to be allowed to change things at all. Beyond that:\n\n")
	b.WriteString("- **Roles**: the caller must hold one of these in the namespace (`@role`). *any* means no role is asked for.\n")
	b.WriteString("- **Allowed when**: one of these rules must hold for the caller's attributes (`@allow`). *any caller* means there is no rule. A rule that names a field compares the stored record, so for a list it narrows the rows returned.\n")
	b.WriteString("- **Runs**: *planned first* means the command answers a plan and runs only when that plan's id is run (`@plan`).\n\n")
	b.WriteString("This is what the schema declares. A deployment's own policy can allow or refuse beyond it.\n\n")

	type command struct {
		on string
		c  *schema.Command
	}
	var commands []command
	for _, a := range s.Aggregates {
		for _, c := range a.Commands {
			commands = append(commands, command{a.Name, c})
		}
	}
	for _, r := range s.Records {
		for _, c := range r.Commands {
			commands = append(commands, command{r.Name, c})
		}
	}
	sort.Slice(commands, func(i, j int) bool { return lowerFirst(commands[i].c.Name) < lowerFirst(commands[j].c.Name) })
	b.WriteString("## Commands\n\n")
	if len(commands) == 0 {
		b.WriteString("None.\n\n")
	} else {
		b.WriteString("| Command | On | Roles | Allowed when | Runs |\n|---|---|---|---|---|\n")
		for _, cmd := range commands {
			runs := "at once"
			if cmd.c.Plan {
				runs = "planned first"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", lowerFirst(cmd.c.Name), cmd.on, accessRoles(cmd.c.Roles), accessRules(cmd.c.Allow), runs)
		}
		b.WriteString("\n")
	}

	type read struct {
		name, of string
		roles    []string
		rules    []*schema.Rule
	}
	var reads []read
	for _, a := range s.Aggregates {
		reads = append(reads, read{lowerFirst(a.Name), a.Name, a.ReadRoles, a.ReadAllow})
		if a.Table {
			reads = append(reads, read{lowerFirst(a.Name) + "s", a.Name, a.ReadRoles, a.ReadAllow})
		}
	}
	for _, r := range s.Records {
		reads = append(reads, read{lowerFirst(r.Name), r.Name, r.ReadRoles, r.ReadAllow}, read{lowerFirst(r.Name) + "s", r.Name, r.ReadRoles, r.ReadAllow})
	}
	for _, e := range s.Entities {
		reads = append(reads, read{lowerFirst(e.Name), e.Name, e.ReadRoles, e.ReadAllow}, read{lowerFirst(e.Name) + "s", e.Name, e.ReadRoles, e.ReadAllow})
	}
	sort.Slice(reads, func(i, j int) bool { return reads[i].name < reads[j].name })
	b.WriteString("## Reads\n\nA read's subscription (`…Changed`) is gated as the read is.\n\n")
	if len(reads) == 0 {
		b.WriteString("None.\n")
	} else {
		b.WriteString("| Read | Of | Roles | Allowed when |\n|---|---|---|---|\n")
		for _, r := range reads {
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.name, r.of, accessRoles(r.roles), accessRules(r.rules))
		}
	}
	return []byte(b.String()), nil
}

func accessRoles(roles []string) string {
	if len(roles) == 0 {
		return "*any*"
	}
	return strings.Join(roles, ", ")
}

// accessRules reads the @allow rules aloud: pairs joined by "and",
// rules by "or", each rule's pairs in a fixed order.
func accessRules(rules []*schema.Rule) string {
	if len(rules) == 0 {
		return "*any caller*"
	}
	said := make([]string, len(rules))
	for i, r := range rules {
		var parts []string
		for _, attr := range pairKeys(r.Caller) {
			parts = append(parts, fmt.Sprintf("`%s` is `%s`", attr, r.Caller[attr]))
		}
		for _, f := range pairKeys(r.Own) {
			parts = append(parts, fmt.Sprintf("its `%s` is the caller's `%s`", f, r.Own[f]))
		}
		said[i] = strings.Join(parts, " and ")
	}
	return strings.Join(said, "; **or** ")
}

func pairKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
